#!/usr/bin/env python3
"""Write docs/COMMITS.md: every hand-made commit (not the Action's "Rebuild site" commits), oldest first,
with date, author, message and the source files it touched. Generated files (built HTML, converted media,
résumé PDFs/PNGs) are left out of the file lists so the list shows what a person or agent actually changed.

Run from the repo root:  python3 tools/commit_log.py
Machine-readable: each commit is one "### <hash> · <date> · <author>" heading followed by its message
and a "files:" line (comma-separated paths). CHANGELOG.md is the hand-written summary of the same history.
"""
import subprocess, re
from collections import OrderedDict

GENERATED = re.compile(r"^(index|gallery|lab|cv|tv)\.html$|^(projects|code)/.*\.html$|^snippets/|^cv/|"
                       r"^Roee-Tal-CV\.pdf$|^assets/(img|thumbs|full|posters|clips|art|cv)/|__pycache__")

def main():
    out = subprocess.run(["git", "log", "--reverse", "--name-only", "--date=short",
                          "--format=@@%h|%ad|%an|%s"], capture_output=True, text=True, check=True).stdout
    commits, cur = [], None
    for line in out.splitlines():
        if line.startswith("@@"):
            h, d, a, s = line[2:].split("|", 3)
            cur = {"h": h, "d": d, "a": a, "s": s, "f": []}; commits.append(cur)
        elif line.strip() and cur:
            cur["f"].append(line.strip())
    commits = [c for c in commits if not c["s"].startswith("Rebuild site")]
    days = OrderedDict()
    for c in commits: days.setdefault(c["d"], []).append(c)
    w = ["# Commit log (generated)", "",
         "Generated by `tools/commit_log.py` — do not edit by hand. Hand-written summary: [CHANGELOG.md](../CHANGELOG.md).",
         "Left out: the Action's `Rebuild site [skip ci]` commits and generated files (built HTML, media copies, résumé PDFs/PNGs).",
         "Authors: `Claude` = AI coding sessions; `Roee Tal` = the owner's account (his own edits, other AI agents working as him,",
         "and `Edit on the site: …` commits made by the visual editor's Publish button).", "",
         f"Total: {len(commits)} commits.", ""]
    for d, cs in days.items():
        w += [f"## {d}", ""]
        for c in cs:
            src = [f for f in c["f"] if not GENERATED.search(f)]
            w += [f"### {c['h']} · {d} · {c['a']}", c["s"], "",
                  "files: " + (", ".join(src) if src else "(only pages or media — before build.py these were hand-written)"), ""]
    open("docs/COMMITS.md", "w").write("\n".join(w))
    print(f"docs/COMMITS.md: {len(commits)} commits")

if __name__ == "__main__":
    main()
